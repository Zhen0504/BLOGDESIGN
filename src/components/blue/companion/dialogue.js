export const dialogueTopic=(state,expression)=>['willing','resisting','flipping','settling','wall','portal','walking','roll','melt','lie','spin','stretch','peek','sideLie','lookBack','pounce','sway'].includes(state)?state:expression
export class DialogueDirector{
  constructor(random=Math.random){this.random=random;this.topic='';this.line='';this.next=0;this.until=0;this.responseKey='';this.history=new Map()}
  update(topic,now,{reading=false,response={}}={}){
    const previous=this.topic,changed=previous!==topic
    const key=response.phase?`${response.id||0}:${response.phase}`:''
    let cue=''
    if(key!==this.responseKey){
      if(response.phase==='dizzy')cue='dizzy'
      else if(response.phase?.endsWith('-happy'))cue='happy'
    }
    const actions=['peek','sideLie','lookBack','pounce','sway','melt','spin','walking']
    if(!cue&&changed){
      if(['willing','resisting','flipping','wall','portal'].includes(topic))cue=topic
      else if(actions.includes(previous))cue=previous
    }
    this.topic=topic;this.responseKey=key
    if(now>=this.until)this.line=''
    if(!cue||this.line||now<this.next||this.random()>.72)return this.line
    const pool=lines[cue]||lines.calm
    const choices=pool.filter(line=>now-(this.history.get(line)??-Infinity)>120)
    if(!choices.length)return this.line
    this.line=choices[Math.min(choices.length-1,Math.floor(this.random()*choices.length))]
    this.history.set(this.line,now)
    this.until=now+Math.max(4,Math.min(8,2.8+[...this.line].length*.18))
    this.next=this.until+(reading?18:10)+this.random()*6
    return this.line
  }
}
