import assert from 'node:assert/strict'
import {CompanionResponses} from '../../src/components/blue/companion/responses.js'
import {DialogueDirector} from '../../src/components/blue/companion/dialogue.js'
import {chooseReadingIdleAction} from '../../src/components/blue/companion/idleActions.js'

const pet=new CompanionResponses()
pet.tap(0,-1)
assert.equal(pet.update(.1).expression,'curious')
const side=pet.update(.8)
assert.ok(side.pose.turn<-.5,'a real side glance, not just a face change')
assert.equal(pet.update(1.7).expression,'happy','curiosity comes before delight')
assert.equal(pet.update(3.3).phase,'')
pet.tap(4,1)
assert.ok(pet.update(4.8).pose.turn>.5)
assert.equal(pet.update(5,{busy:true}).phase,'','drag/flip interrupts a small response')
assert.equal(pet.update(6).phase,'')
assert.equal(pet.update(7,{dizzy:true}).expression,'dizzy')
assert.equal(pet.tap(7.5),false,'tapping does not clear dizziness')
pet.update(11,{dizzy:true})
const start=pet.update(12),blink=pet.update(12.15),settled=pet.update(12.8)
assert.equal(start.phase,'recovering');assert.equal(blink.blink,0)
assert.equal(start.expression,'calm');assert.ok(start.sway>settled.sway)
assert.equal(pet.update(13.2).phase,'','recovery ends, no extra idle animation')
pet.enter(14);pet.leave(15);pet.enter(25)
assert.equal(pet.update(25).phase,'','brief absence is not a reunion')
pet.leave(26);pet.enter(47)
assert.equal(pet.update(47.5).phase,'return-curious')
pet.update(51);pet.leave(52);pet.enter(73)
assert.equal(pet.update(73).phase,'','greetings have a thirty-second cooldown')
const accessible=new CompanionResponses();accessible.tap(0)
assert.deepEqual(accessible.update(.5,{reduced:true}).pose,{})

const speech=new DialogueDirector(()=>0)
for(let i=0;i<60;i++)assert.equal(speech.update(i%2?'happy':'curious',i),'','no passive chatter')
const line=speech.update('happy',61,{response:{phase:'tap-happy',id:1},reading:true})
assert.ok(line.length>0)
const duration=speech.until-61
assert.ok(duration>=4&&duration<=8)
assert.equal(speech.update('wall',62),line,'an event cannot replace a line before it can be read')
assert.equal(speech.update('calm',70),'')
assert.equal(speech.update('resisting',71),'','reading cooldown suppresses the next event')
speech.update('calm',100)
const different=speech.update('happy',101,{response:{phase:'tap-happy',id:2}})
assert.ok(different&&different!==line,'two-minute recent-history protection')
const silent=new DialogueDirector(()=>.99)
assert.equal(silent.update('wall',1),'','not every interaction needs a line')
const reading=new Set(Array.from({length:100},(_,i)=>chooseReadingIdleAction(()=>i/100)))
assert.ok(reading.has('peek'));assert.equal(reading.has('pounce'),false);assert.equal(reading.has('spin'),false)
console.log('Side-glance response, greeting cooldown, blink/settle recovery, quiet reading and event-based speech passed.')
