import assert from 'node:assert/strict'
import {expressions,expressionById} from '../../src/components/blue/companion/expressions.js'
import {lines,DialogueDirector,dialogueTopic} from '../../src/components/blue/companion/dialogue.js'
import {createGelMaterial} from '../../src/components/blue/companion/gelMaterial.js'
assert.equal(expressions.length,11)
assert.equal(new Set(expressions.map(e=>e.id)).size,11)
assert.equal(expressionById('dizzy').eyes[0].kind,'spiral')
assert.equal(expressionById('angry').anger,1)
assert.equal(expressionById('shy').blush,1)
assert.equal(expressionById('shy').eyes[0].kind,'chevron')
assert.notDeepEqual(expressionById('sleepy').eyes,expressionById('focused').eyes)
assert.equal(Object.values(lines).flat().length,138)
assert.equal(new Set(Object.values(lines).flat()).size,138)
for(const e of expressions)assert.equal(lines[e.id].length,6)
const director=new DialogueDirector(()=>0)
assert.equal(director.update('shy',0),'','passive expressions do not chatter')
const first=director.update(dialogueTopic('resisting','angry'),1)
assert.ok(lines.resisting.includes(first))
assert.equal(director.update('resisting',2),first)
assert.equal(director.update('resisting',10),'','speech expires even when mood persists')
director.update('calm',30)
assert.notEqual(director.update('resisting',31),first,'recent lines are not repeated')
const material=createGelMaterial()
assert.equal(material.userData.emotionUniforms.gelAnger.value,0)
assert.equal(material.userData.emotionUniforms.gelBlush.value,0)
assert.equal(material.opacity,1)
assert.equal(material.transmission,1)
material.dispose()
console.log('11 expressions, 138 unique contextual lines, non-repeating dialogue and gel emotion uniforms passed.')
