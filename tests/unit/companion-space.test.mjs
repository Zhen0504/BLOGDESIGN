import assert from 'node:assert/strict'
import {CompanionSpace,companionLayout} from '../../src/components/blue/companion/space.js'
const layout=companionLayout({width:1440,height:1000,home:false,left:true,column:{left:380,right:1060}})
const step=(s,n=120)=>{let p;for(let i=0;i<n;i++)p=s.tick(1/60);return p}
let calls=0
const wall=new CompanionSpace(layout,()=>{calls++;return .1})
wall.begin({x:190,y:580});wall.move({x:800,y:580})
assert.equal(wall.contact.kind,'wall');assert.equal(calls,1)
step(wall);assert.ok(wall.x+wall.size/2<layout.column.left)
for(let i=0;i<20;i++)wall.move({x:850+i,y:580})
assert.equal(calls,1,'one fixed boundary decision per drag')
wall.end();assert.equal(wall.contact,null)
const portal=new CompanionSpace(layout,()=>.9)
portal.begin({x:190,y:580});portal.move({x:800,y:580})
assert.equal(portal.travel,null,'pointer alone does not trigger passage')
step(portal,30)
assert.equal(portal.travel.kind,'portal')
const before=portal.x;step(portal,50);assert.ok(portal.x>before&&portal.x<1200,'continuous intermediate position')
portal.end();step(portal,120);assert.equal(portal.travel,null);assert.ok(portal.x>layout.column.right)
const walking=new CompanionSpace(layout)
const to=companionLayout({width:1440,height:1000,home:false,left:false,column:{left:380,right:1060}})
walking.setLayout(to);assert.equal(walking.x,190,'route change never teleports')
step(walking,30);assert.ok(walking.x>190&&walking.x<1250)
step(walking,200);assert.equal(walking.x,to.anchor.x)
const home=companionLayout({width:1440,height:1000,home:true})
const tank=new CompanionSpace(home,()=>0)
tank.begin(home.anchor);tank.move({x:-900,y:-900});step(tank)
assert.ok(tank.x-tank.size/2>home.tank.left);assert.ok(tank.y-tank.size/2>home.tank.top)
const mobile=companionLayout({width:390,height:844,home:false,left:true})
assert.ok(mobile.bounds.right-mobile.bounds.left>230,'mobile can traverse the reading dock')
assert.ok(mobile.bounds.top<=mobile.bounds.bottom)
console.log('Tank bounds, expanded reading space, fixed wall/portal choice, continuous route walk and mobile dock passed.')
const threshold=new CompanionSpace(layout,()=>.9)
threshold.begin({x:190,y:580});threshold.move({x:300,y:580});step(threshold,30)
assert.equal(threshold.travel,null,'less than one third penetration stays manual')
threshold.move({x:370,y:580});step(threshold,30)
assert.equal(threshold.travel.kind,'portal')
const idle=new CompanionSpace(layout,()=>.8)
step(idle,1439);assert.equal(idle.travel,null)
step(idle,4);assert.equal(idle.travel?.roaming,true)
idle.interact();assert.equal(idle.travel,null)
